// Command workload-instrument derives test-only lookup instrumentation from the
// current production BPE methods. It never changes the timed implementation.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "fail if committed instrumentation is stale")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	selected := map[string]bool{"Tokenize": true, "mergeAll": true, "mergeArray": true, "updateArrayPair": true, "mergeHeap": true}
	fset := token.NewFileSet()
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./tools/workload-instrument; DO NOT EDIT.\n\npackage model\n\n")
	for _, name := range []string{"encode.go", "merge.go"} {
		file, err := parser.ParseFile(fset, filepath.Join(root, "internal/model", name), nil, 0)
		if err != nil {
			return err
		}
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || !selected[fn.Name.Name] {
				continue
			}
			delete(selected, fn.Name.Name)
			fn.Recv.List[0].Type = &ast.StarExpr{X: ast.NewIdent("WorkloadAnalyzer")}
			lookup := 0
			ast.Inspect(fn.Body, func(n ast.Node) bool {
				assign, ok := n.(*ast.AssignStmt)
				if !ok || len(assign.Rhs) != 1 {
					return true
				}
				index, ok := assign.Rhs[0].(*ast.IndexExpr)
				if !ok {
					return true
				}
				selector, ok := index.X.(*ast.SelectorExpr)
				if !ok || selector.Sel.Name != "merges" {
					return true
				}
				lookup++
				assign.Rhs[0] = &ast.CallExpr{
					Fun:  &ast.SelectorExpr{X: selector.X, Sel: ast.NewIdent("lookup")},
					Args: []ast.Expr{index.Index, &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote(fmt.Sprintf("%s.%d", fn.Name.Name, lookup))}},
				}
				return true
			})
			// Reject new or removed lookup sites rather than silently omitting them.
			want := map[string]int{"Tokenize": 0, "mergeHeap": 2, "mergeAll": 1, "mergeArray": 0, "updateArrayPair": 1}[fn.Name.Name]
			if lookup != want {
				return fmt.Errorf("%s has %d lookup sites, expected %d; review instrumentation", fn.Name.Name, lookup, want)
			}
			if err := format.Node(&out, fset, fn); err != nil {
				return err
			}
			out.WriteString("\n\n")
		}
	}
	if len(selected) != 0 {
		return fmt.Errorf("missing production methods: %v", selected)
	}
	data, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	path := filepath.Join(root, "internal/model/workload_generated_test.go")
	if check {
		current, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, data) {
			return fmt.Errorf("stale workload instrumentation: go run ./tools/workload-instrument")
		}
		return nil
	}
	return os.WriteFile(path, data, 0644)
}
